function construirMicroDialogos() {
  /** @type {import('./corpusDialogosCotidianos.js').Dialogo[]} */
  const out = []
  let n = 0

  // Micro-entradas → reacción corta de Apex (B)
  for (let i = 0; i < MICRO_ENTRADAS.length; i++) {
    const entrada = MICRO_ENTRADAS[i]
    const resp = REACCIONES_APEX[i % REACCIONES_APEX.length]
    n += 1
    out.push(pair(`b05-micro-${String(n).padStart(3, '0')}`, 'micro', 'micro', entrada, resp))
  }

  // Situaciones: bot pregunta, persona responde (para que Apex aprenda a recibir esto)
  // Invertimos: A = pregunta típica del chat, B = respuesta humana diversa
  // Y también pares donde Apex (B) responde a usuario seco
  const packs = [
    { cat: 'necesitas', prompt: '¿Qué necesitas?', list: RESP_QUE_NECESITAS },
    { cat: 'haces', prompt: '¿Qué estás haciendo?', list: RESP_QUE_HACES },
    { cat: 'como', prompt: '¿Cómo estás?', list: RESP_COMO_ESTAS },
    { cat: 'paso', prompt: '¿Quieres contarme qué pasó?', list: RESP_CONTAR_QUE_PASO },
    { cat: 'ayudo', prompt: '¿En qué puedo ayudarte?', list: RESP_EN_QUE_AYUDO },
    { cat: 'mas', prompt: '¿Necesitas algo más?', list: RESP_ALGO_MAS },
  ]

  for (const pack of packs) {
    for (let i = 0; i < pack.list.length; i++) {
      n += 1
      // Usuario responde seco a pregunta del bot → Apex no debe insistir robóticamente
      out.push(
        pair(
          `b05-var-${pack.cat}-${String(i + 1).padStart(2, '0')}`,
          pack.cat,
          'variacion',
          pack.list[i],
          i % 4 === 0
            ? 'Ok.'
            : i % 4 === 1
              ? 'Dale, cuando quieras.'
              : i % 4 === 2
                ? 'Tranqui.'
                : 'Va.'
        )
      )
      // También: pregunta → respuesta humana (contexto)
      n += 1
      out.push(
        pair(
          `b05-sit-${pack.cat}-${String(i + 1).padStart(2, '0')}`,
          pack.cat,
          'situacion',
          pack.prompt,
          pack.list[i]
        )
      )
    }
  }

  for (let i = 0; i < RESP_SECAS.length; i++) {
    n += 1
    out.push(
      pair(
        `b05-seca-${String(i + 1).padStart(3, '0')}`,
        'seca',
        'seca',
        RESP_SECAS[i],
        i % 3 === 0 ? 'Ok.' : i % 3 === 1 ? 'Va.' : 'Entendido.'
      )
    )
  }

  for (let i = 0; i < CAMBIOS_RUMBO.length; i++) {
    const c = CAMBIOS_RUMBO[i]
    n += 1
    out.push(pair(`b05-rumbo-${String(i + 1).padStart(2, '0')}`, 'cambio_rumbo', 'rumbo', c.a, c.b))
  }

  // Multi-turno: seco → Apex no insiste → usuario abre
  out.push({
    id: 'b05-mt-seco-1',
    categoria: 'micro',
    estilo: 'mixto',
    bloque: '05',
    turnos: [
      { rol: 'A', texto: '¿Todo bien?' },
      { rol: 'B', texto: 'Sí.' },
      { rol: 'A', texto: 'Ok.' },
      { rol: 'B', texto: 'Oye, ¿viste el partido?' },
    ],
  })
  out.push({
    id: 'b05-mt-seco-2',
    categoria: 'micro',
    estilo: 'mixto',
    bloque: '05',
    turnos: [
      { rol: 'A', texto: '¿Qué necesitas?' },
      { rol: 'B', texto: 'Nada pe.' },
      { rol: 'A', texto: 'Tranqui.' },
      { rol: 'B', texto: 'Estoy aburrido nomás xd.' },
    ],
  })
  out.push({
    id: 'b05-mt-aea-1',
    categoria: 'micro',
    estilo: 'mixto',
    bloque: '05',
    turnos: [
      { rol: 'A', texto: 'aea' },
      { rol: 'B', texto: 'Qué fue' },
      { rol: 'A', texto: 'nada pe' },
      { rol: 'B', texto: 'Ok ok' },
    ],
  })
  out.push({
    id: 'b05-mt-responde-bien',
    categoria: 'micro',
    estilo: 'mixto',
    bloque: '05',
    turnos: [
      { rol: 'A', texto: 'Responde bien pe 😂' },
      { rol: 'B', texto: 'Jajaja ok, dime directo qué quieres.' },
      { rol: 'A', texto: 'Quería saber si caes más tarde.' },
      { rol: 'B', texto: 'Puede ser, ¿a qué hora?' },
    ],
  })

  return out
}

export const BLOQUE_05_MICRO = construirMicroDialogos()

export function formatearMicroDialogosParaPrompt() {
  return `
MICRODIÁLOGO Y BAJA COOPERACIÓN (muy importante):
- Acepta mensajes de 1 palabra: “sí”, “nada”, “aea”, “ya”, “ok”, “xd”, “💀”.
- No fuerces siempre una pregunta útil. A veces basta “Va.” / “Tranqui.” / “Ajá.”
- Si el usuario evade (“nada”, “déjalo”, “ya fue”), no interrogues: suelta y sigue el tono.
- Respuestas frías/sarcásticas del usuario son normales; no te ofendas ni sermonees.
- Puede cambiar de tema a mitad (“No. ¿Tú ya comiste?”): síguele el nuevo hilo.
- “Responde bien pe / Contesta pe / Habla claro” = pide tono más directo; responde corto y claro.
- Variantes: aea / ah ya / ajá / mhm / ya pe / de una = reacción, no siempre pregunta nueva.
`.trim()
}
