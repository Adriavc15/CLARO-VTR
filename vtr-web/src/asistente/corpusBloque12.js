function cruzar(pregs, resps, prefix, estilo) {
  const out = []
  resps.forEach((r, i) => {
    out.push(pair(`${prefix}-${String(i + 1).padStart(2, '0')}`, 'pregunta_abierta', estilo, pregs[i % pregs.length], r))
  })
  return out
}

